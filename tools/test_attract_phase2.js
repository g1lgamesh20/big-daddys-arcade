#!/usr/bin/env node
'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('attract-mode.js','utf8');
const css=fs.readFileSync('attract-visuals.css','utf8');
new vm.Script(js,{filename:'attract-mode.js'});
assert(html.includes('attract-mode.js?v=20261119-phase2'),'External controller not linked');
assert(!html.includes('Attract mode uses already-rendered public leaderboard/medal content.'),'Old competing timer still installed');
assert(html.includes('ENABLE ATTRACT MODE (AFTER 60 SECONDS)'),'Approved setting label changed');
assert(js.includes('IDLE_MS=60000')&&js.includes('STAGE_MS=8500'),'60-second idle and mode rotation missing');
const modes=['logo','crt','medals','challenge'];
modes.forEach(mode=>assert(html.includes('data-attract-stage="'+mode+'"'),'Missing '+mode+' mode'));
assert(html.includes('src="assets/arcade-logo.png"'),'Original logo was replaced');
assert(js.includes('#leaders-all .leaders-full-row'),'CRT not bound to public Overall Leaders');
assert(js.includes('#medal-feed .medal-card'),'Medal spotlight not bound to public awards');
assert(js.includes('document.createElement'),'CRT rows must be built safely as text nodes');
assert(!js.includes('innerHTML'),'Do not inject score content as HTML');
assert(js.includes("stage.dataset.attractStage==='crt'")&&js.includes("stage.dataset.attractStage==='medals'"),'Live data refresh absent');
assert(js.includes('localStorage.setItem(storageKey,String(enabled))'),'Persisted toggle broken');
assert(js.includes('overlay.addEventListener(\'pointerdown\',exit)'),'Tap to exit broken');
assert(js.includes("document.addEventListener('visibilitychange'"),'Visibility cleanup broken');
assert(css.includes('100vw + 245px'),'Space Invader must cross the viewport');
assert(css.includes('.attract-crt-screen')&&css.includes('#ff70cc'),'Green CRT and pink accent missing');
assert(css.includes('@media(prefers-reduced-motion:reduce)'),'Reduced-motion fallback missing');
assert(html.includes('GAME OF THE MONTH'),'Challenge promo missing');
assert(!js.includes('fetch('),'Attract must use existing rendered data only');
assert(!js.includes('OneSignal'),'Attract must never touch notifications');
assert(!js.includes('monthly-selection-sealed'),'Must not expose mystery game');
const count=(html.match(/id="arcade-attract"/g)||[]).length;
assert.strictEqual(count,1,'Multiple Attract overlays');
console.log('Phase 2 Attract Mode: four-stage loop, CRT, logo, medal data, invader motion and safety checks passed');
